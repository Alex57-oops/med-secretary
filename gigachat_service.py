def _make_client():
    return GigaChat(
        credentials=CREDENTIALS,
        scope=SCOPE,
        model=MODEL,
        verify_ssl_certs=False,
        timeout=TIMEOUT,
    )


def _ask(client, prompt):
    """Один запрос с retry при 429."""
    last_error = None
    for attempt in range(MAX_RETRIES):
        try:
            chat = Chat(
                messages=[
                    Messages(role=MessagesRole.SYSTEM, content=SYSTEM_PROMPT),
                    Messages(role=MessagesRole.USER, content=prompt),
                ]
            )
            response = client.chat(chat)
            return response.choices[0].message.content.strip()
        except Exception as e:
            last_error = e
            err_str = str(e)
            # 429 — превышение лимита, ждём и пробуем снова
            if '429' in err_str or 'Too Many Requests' in err_str:
                time.sleep(RETRY_DELAY)
                continue
            # Другие ошибки — не retry
            raise
    raise last_error


def generate_documents(transcript, existing_documents=None):
    """
    Последовательные запросы:
    1) Диаризация.
    2) SOAP.
    3) Направления.
    4) Рецепты.
    Между запросами — пауза 2 сек, чтобы не ловить 429.
    """
    if not transcript or len(transcript.strip()) < 20:
        raise ValueError("Слишком короткий текст приёма.")

    with _make_client() as client:
        # 1. Диаризация
        if existing_documents:
            dialogue = _ask(client, PROMPT_DIARIZE_UPDATE.format(
                transcript=transcript,
                existing_dialogue=existing_documents.get('dialogue', ''),
            ))
        else:
            dialogue = _ask(client, PROMPT_DIARIZE.format(transcript=transcript))

        time.sleep(2)

        # 2. SOAP
        soap = _ask(client, PROMPT_SOAP.format(transcript=dialogue))
        time.sleep(2)

        # 3. Направления
        referrals = _ask(client, PROMPT_REFERRALS.format(transcript=dialogue))
        time.sleep(2)

        # 4. Рецепты
        prescriptions = _ask(client, PROMPT_PRESCRIPTIONS.format(transcript=dialogue))

    return {
        "dialogue": dialogue,
        "soap": soap,
        "referrals": referrals,
        "prescriptions": prescriptions,
    }